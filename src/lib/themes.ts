
export interface ThemeDefinition {
  name: string;
  swatchColor: string; // HSL format string "H S% L%"
  symbol?: '●' | '■' | '★';
  light: { [key: string]: string }; // CSS variables in HSL format
  dark: { [key: string]: string }; // CSS variables in HSL format
}

export type AppThemes = Record<ThemeCategory, ThemeDefinition[]>;

export type ThemeCategory = 'customThemes' | 'bespokeThemes' | 'primaryColorsThemes' | 'daisyUIThemes' | 'greyscaleThemes';


const createTheme = (
  name: string,
  primaryColor: string,
  accentColor: string
): ThemeDefinition => ({
  name,
  swatchColor: primaryColor,
  light: {
    '--primary': primaryColor,
    '--accent': accentColor,
  },
  dark: {
    '--primary': primaryColor,
    '--accent': accentColor.replace(/(\d+%)/g, '15%'),
  },
});

